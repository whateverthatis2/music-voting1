# ===========================================================================
# 2. Обчислення характеристик системи (lab5.compute() + ρ та S)
# ===========================================================================

def compute(pi: Sequence[float], graph: Dict = GRAPH_V8) -> Dict:
    """
    Розширює lab5.compute() двома метриками з пп.3-4 завдання Лаб.6:
        ρ = r / Σπ_i           — завантаженість усієї системи
        S = r / max π_i         — прискорення системи

    Повертає словник, що містить усе з lab5.compute(), плюс:
        rho             — ρ ∈ (0, 1]
        speedup         — S
        max_pi          — максимальна пікова продуктивність серед усіх пристроїв
        max_pi_nodes    — список вузлів з π = max π_i
    """
    base = L5.compute(pi, graph=graph)

    pi = [float(v) for v in pi]
    sum_pi = base["sum_peak"]
    max_pi = max(pi)
    max_pi_nodes = [i for i, v in enumerate(pi) if v == max_pi]
    r = base["total_real"]

    base["rho"] = r / sum_pi if sum_pi else 0.0
    base["speedup"] = r / max_pi if max_pi else 0.0
    base["max_pi"] = max_pi
    base["max_pi_nodes"] = max_pi_nodes
    return base


